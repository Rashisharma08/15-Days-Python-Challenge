# Python Day 3 - Loops

# 1. For Loop Example
print("For Loop Example:")
for i in range(1,6):
    print(i)

print()

# 2. Printing in Same Line
print("Same Line Printing:")
for i in range(1,6):
    print(i, end=" ")

print("\n")

# 3. While Loop Example
print("While Loop Example:")
i = 1
while i <= 5:
    print(i)
    i += 1

print()

# 4. Star Pattern
print("Star Pattern:")
for i in range(1,5):
    print("*" * i)
